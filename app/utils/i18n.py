_CURRENT_LANGUAGE = "tr"


def set_language(lang_code: str) -> None:
    """Set active application language ('tr' or 'en')."""
    global _CURRENT_LANGUAGE
    if lang_code in TRANSLATIONS:
        _CURRENT_LANGUAGE = lang_code


def get_language() -> str:
    """Get active language code."""
    return _CURRENT_LANGUAGE


def tr(key: str, **kwargs: Any) -> str:
    """Translate key to current language with optional formatting."""
    lang_dict = TRANSLATIONS.get(_CURRENT_LANGUAGE, TRANSLATIONS["tr"])
    text = lang_dict.get(key, TRANSLATIONS["en"].get(key, key))
    if kwargs:
        try:
            return text.format(**kwargs)
        except Exception:
            return text
    return text

